"""The independent transfer item: a fresh problem of the same kind, no hints (Interface.md "First fixture").

Generated by deterministic code, not a model, so the reference answer is exact and the
check is the same maths checker used for the student's own working. Anything the patterns
below do not recognise returns None and the caller falls back to a closing question.
"""

from __future__ import annotations

import re
from typing import Optional

from .presets import PRESETS, Preset

_QUAD = re.compile(r"^x\*\*2(?:([+-])(\d*)\*?x)?([+-]\d+)?=0$")
_LINEAR = re.compile(r"^(\d*)\*?x([+-]\d+)=(-?\d+)$")
_SHIFTS = [(-1, -2), (1, 2), (-2, -3), (2, 1), (-3, -1), (3, 2), (-1, -3), (1, 3)]
_SUPER = str.maketrans("0123456789-", "⁰¹²³⁴⁵⁶⁷⁸⁹⁻")


def _sign(n: int, first: bool = False) -> str:
    if first:
        return "-" if n < 0 else ""
    return " − " if n < 0 else " + "


def _fmt_quad(b: int, c: int) -> tuple[str, str]:
    parts = ["x²"]
    if b:
        parts.append(f"{_sign(b)}{'' if abs(b) == 1 else abs(b)}x")
    if c:
        parts.append(f"{_sign(c)}{abs(c)}")
    display = "".join(parts) + " = 0"
    expr = "x**2" + (f"{b:+d}*x" if b else "") + (f"{c:+d}" if c else "") + "=0"
    return display, expr


def _quad_roots(b: int, c: int) -> Optional[tuple[int, int]]:
    disc = b * b - 4 * c
    if disc < 0:
        return None
    r = int(round(disc ** 0.5))
    if r * r != disc or (-b + r) % 2:
        return None
    return (-b + r) // 2, (-b - r) // 2


def make_transfer(statement_expr: Optional[str], preset: Optional[Preset] = None) -> Optional[tuple[str, str]]:
    """Return ``(display text, statement_expr)`` for a fresh problem, or None if none can be made."""
    if preset is not None and preset.transfer:
        return preset.transfer
    if not statement_expr:
        return None
    s = statement_expr.replace(" ", "")
    m = _QUAD.match(s)
    if m:
        sign, mag, const = m.groups()
        b = (0 if sign is None else (1 if mag == "" else int(mag)) * (-1 if sign == "-" else 1))
        c = int(const) if const else 0
        roots = _quad_roots(b, c)
        if roots is None:
            return None
        original = sorted(roots)
        for d1, d2 in _SHIFTS:
            p, q = roots[0] + d1, roots[1] + d2
            if p == 0 or q == 0 or sorted((p, q)) == original or p == q:
                continue
            return _fmt_quad(-(p + q), p * q)
        return None
    m = _LINEAR.match(s)
    if m:
        a = int(m.group(1)) if m.group(1) else 1
        b, c = int(m.group(2)), int(m.group(3))
        if a == 0 or (c - b) % a:
            return None
        x0 = (c - b) // a
        a2, x2 = a + 1, x0 + 1
        c2 = a2 * x2 + b
        sign = "−" if b < 0 else "+"
        return f"{a2}x {sign} {abs(b)} = {c2}", f"{a2}*x{b:+d}={c2}"
    return None


def preset_for(preset_id: Optional[str]) -> Optional[Preset]:
    return PRESETS.get(preset_id or "")


def simple_answer(statement_expr: str) -> Optional[str]:
    """The exact answer for the two equation shapes this module generates, as ``x=a or x=b``."""
    s = statement_expr.replace(" ", "")
    m = _QUAD.match(s)
    if m:
        sign, mag, const = m.groups()
        b = (0 if sign is None else (1 if mag == "" else int(mag)) * (-1 if sign == "-" else 1))
        roots = _quad_roots(b, int(const) if const else 0)
        if roots is None:
            return None
        lo, hi = sorted(set(roots))[0], sorted(set(roots))[-1]
        return f"x={lo}" if lo == hi else f"x={lo} or x={hi}"
    m = _LINEAR.match(s)
    if m:
        a = int(m.group(1)) if m.group(1) else 1
        b, c = int(m.group(2)), int(m.group(3))
        if a and (c - b) % a == 0:
            return f"x={(c - b) // a}"
    return None
